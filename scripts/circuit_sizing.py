#!/usr/bin/env python3
"""Generate docs/CIRCUIT_SIZING.md: the measured workload a ZIP 2007 transparent
recovery circuit would face, from web/data (summary.json, top.json, p2sh_survey.json).

    python3 scripts/circuit_sizing.py
"""
import json
import os
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = pathlib.Path(os.environ.get("SHORLINE_DATA", ROOT / "web" / "data"))
S = json.loads((DATA / "summary.json").read_text())
TOP = json.loads((DATA / "top.json").read_text())
P2 = json.loads((DATA / "p2sh_survey.json").read_text())

zec = lambda z: f"{z / 1e8:,.0f}"
pct = lambda a, b: f"{100 * a / b:.1f}%" if b else "n/a"
cats = {c["id"]: c for c in S["transparent"]["categories"]}
h = cats["p2pkh_hidden"]
tt = S["transparent"]["total_zat"]
height = S["chain"]["height"]

# Concentration among the largest hidden t1 addresses (top.json holds the top N).
hid = sorted(TOP["p2pkh_hidden"], key=lambda e: -e["zat"])
n_top = len(hid)
rows = []
for k in (1, 10, 100):
    if k <= n_top:
        rows.append((k, sum(e["zat"] for e in hid[:k])))

# Multisig shapes among revealed P2SH scripts.
shapes = {}
for e in P2["entries"]:
    r = e["redeem"]
    if "m" in r and "n" in r:
        key = f"{r['m']}-of-{r['n']}" + (" (salted)" if r["type"].startswith("salted") else "")
        a = shapes.setdefault(key, [0, 0])
        a[0] += 1
        a[1] += e["zat"]
shape_rows = sorted(shapes.items(), key=lambda kv: -kv[1][1])

out = f"""# ZIP 2007 circuit sizing

*Generated by `scripts/circuit_sizing.py` from the block {height:,} dataset. Do not edit by hand.*

ZIP 2007 asks whether a transparent recovery circuit is worth building. This page turns Shorline's
measured category sizes into the workload such a circuit would have to handle. It gives counts only.
Proving costs depend on the circuit design and are not estimated here.

## 1. The addressable pool: hash-protected `t1`

| Quantity | Value |
|---|---:|
| Funded `t1` addresses with a never-revealed key | {h['addresses']:,} |
| UTXOs at those addresses | {h['utxos']:,} |
| ZEC at those addresses | {zec(h['zat'])} |
| Share of all transparent ZEC | {pct(h['zat'], tt)} |
| Average UTXOs per address | {h['utxos'] / h['addresses']:.1f} |
| Average ZEC per address | {h['zat'] / 1e8 / h['addresses']:.2f} |

A recovery claim for a `t1` address proves knowledge of a secp256k1 key whose Hash160 equals the address,
so the claim count is bounded by **{h['addresses']:,} statements** if claims are per address, and by
{h['utxos']:,} if a design proves per UTXO. Per-address claiming is {h['utxos'] / h['addresses']:.1f}x cheaper at the
average.

## 2. Concentration

Value is highly concentrated, so a circuit that only serves the largest holders still covers a large share of the value:

| Largest hidden `t1` addresses | ZEC | Share of hidden ZEC |
|---|---:|---:|
""" + "\n".join(f"| top {k} | {zec(z)} | {pct(z, h['zat'])} |" for k, z in rows) + f"""

(`top.json` lists the {n_top} largest.) The long tail is {h['addresses'] - n_top:,} addresses, each
holding less than the {n_top}th-largest balance, together {pct(h['zat'] - rows[-1][1], h['zat'])} of hidden ZEC.

## 3. P2SH is a separate, smaller problem

* **Revealed `t3`** ({cats['p2sh_seen']['addresses']:,} addresses, {zec(cats['p2sh_seen']['zat'])} ZEC): keys are public, so these are *exposed*, not recoverable.
* **Unseen `t3`** ({cats['p2sh_unseen']['addresses']:,} addresses, {zec(cats['p2sh_unseen']['zat'])} ZEC): a recovery circuit would have to prove knowledge of a redeem script hashing to the address.
  The script's shape (m-of-n) must be handled inside the circuit. The shapes seen among revealed scripts, which indicate what unseen ones probably look like:

| Revealed multisig shape | Addresses | ZEC |
|---|---:|---:|
""" + "\n".join(f"| {k} | {a:,} | {zec(z)} |" for k, (a, z) in shape_rows) + f"""

P2SH-wrapped P2PKH/P2PK are rare ({sum(1 for e in P2['entries'] if e['redeem']['type'] in ('p2pkh_wrapped','p2pk_wrapped'))} addresses), so a circuit
that supports only 2-of-3 and 2-of-2 multisig shapes would cover nearly every revealed multisig address.

## 4. What this does not say

* It does not estimate proof size or proving time. Those depend on the circuit design chosen.
* *Hash-protected* is an upper bound on recoverable value: keys can leak off-chain
  (see [FINDINGS.md](FINDINGS.md), Ycash cross-check and METHODOLOGY §7).
* It counts funded addresses at the snapshot height only. Future spends move value from hidden to exposed.
"""
(ROOT / "docs" / "CIRCUIT_SIZING.md").write_text(out)
print("wrote docs/CIRCUIT_SIZING.md")
